# -- deterministic role mapping --------------------------------------------


def test_exactly_one_mapped_role_is_granted() -> None:
    role = resolve_access_role(
        {"groups": ["mdgw-operators"]},
        claim_name="groups",
        role_mapping={
            "mdgw-operators": "Operator",
            "mdgw-admins": "SuperAdmin",
        },
    )

    assert role == "Operator"


def test_a_single_string_claim_value_is_supported() -> None:
    assert (
        resolve_access_role(
            {"groups": "mdgw-auditors"},
            claim_name="groups",
            role_mapping={"mdgw-auditors": "Auditor"},
        )
        == "Auditor"
    )


def test_repeated_group_values_resolve_to_one_role() -> None:
    assert (
        resolve_access_role(
            {"groups": ["mdgw-operators", "mdgw-operators"]},
            claim_name="groups",
            role_mapping={"mdgw-operators": "Operator"},
        )
        == "Operator"
    )


def test_unmapped_claim_is_denied() -> None:
    with pytest.raises(RoleResolutionError) as captured:
        resolve_access_role(
            {"groups": ["unknown-group"]},
            claim_name="groups",
            role_mapping={"mdgw-operators": "Operator"},
        )

    assert captured.value.reason == "role_unmapped"


def test_missing_claim_is_denied_as_unmapped() -> None:
    with pytest.raises(RoleResolutionError) as captured:
        resolve_access_role(
            {},
            claim_name="groups",
            role_mapping={"mdgw-operators": "Operator"},
        )

    assert captured.value.reason == "role_unmapped"


def test_multiple_distinct_roles_conflict() -> None:
    with pytest.raises(RoleResolutionError) as captured:
        resolve_access_role(
            {"groups": ["mdgw-operators", "mdgw-admins"]},
            claim_name="groups",
            role_mapping={
                "mdgw-operators": "Operator",
                "mdgw-admins": "SuperAdmin",
            },
        )

    assert captured.value.reason == "role_conflict"


def test_invalid_claim_shape_is_rejected() -> None:
    with pytest.raises(RoleResolutionError) as captured:
        resolve_access_role(
            {"groups": {"unexpected": "object"}},
            claim_name="groups",
            role_mapping={"mdgw-operators": "Operator"},
        )

    assert captured.value.reason == "role_claim_invalid"


def test_role_resolution_never_consults_the_client_supplied_role() -> None:
    claims = {
        "groups": ["mdgw-operators"],
        "role": "SuperAdmin",
        "access_role": "SuperAdmin",
    }

    assert (
        resolve_access_role(
            claims,
            claim_name="groups",
            role_mapping={"mdgw-operators": "Operator"},
        )
        == "Operator"
    )
