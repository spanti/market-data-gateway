"""Offline OIDC client: discovery/JWKS caches, PKCE, token and claim checks.

No network is used. A fake transport returns canned discovery/JWKS/token
documents, and ID tokens are signed with keys generated by ``cryptography`` so
signature validation runs exactly as it will in production.
"""

from __future__ import annotations

import base64
import hashlib
import json
from dataclasses import dataclass
from typing import Any
from urllib.parse import parse_qs, urlsplit

import pytest
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec, padding, rsa
from cryptography.hazmat.primitives.asymmetric.utils import (
    decode_dss_signature,
)

from mdgw.admin.auth.oidc import (
    IdTokenInvalidError,
    OidcClient,
    OidcDiscoveryError,
    OidcTokenError,
    OidcTransportError,
    RoleResolutionError,
    pkce_challenge,
    resolve_access_role,
)
from mdgw.config import AdminOidcConfig

ISSUER = "https://idp.example.com"
CLIENT_ID = "mdgw-console"
SECRET = "top-secret-value"  # ruff: ignore[hardcoded-password-string]  # fake test secret
NOW_S = 1_800_000_000
NOW_NS = NOW_S * 1_000_000_000


def b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def b64url_decode(value: str) -> bytes:
    padding_needed = "=" * (-len(value) % 4)
    return base64.urlsafe_b64decode(value + padding_needed)


def _int_bytes(value: int, *, length: int | None = None) -> bytes:
    if length is None:
        length = max(1, (value.bit_length() + 7) // 8)
    return value.to_bytes(length, "big")


def rsa_jwk(private_key: rsa.RSAPrivateKey, kid: str) -> dict[str, Any]:
    numbers = private_key.public_key().public_numbers()
    return {
        "kty": "RSA",
        "kid": kid,
        "use": "sig",
        "alg": "RS256",
        "n": b64url(_int_bytes(numbers.n)),
        "e": b64url(_int_bytes(numbers.e)),
    }


def ec_jwk(private_key: ec.EllipticCurvePrivateKey, kid: str) -> dict[str, Any]:
    numbers = private_key.public_key().public_numbers()
    return {
        "kty": "EC",
        "kid": kid,
        "use": "sig",
        "alg": "ES256",
        "crv": "P-256",
        "x": b64url(_int_bytes(numbers.x, length=32)),
        "y": b64url(_int_bytes(numbers.y, length=32)),
    }


def sign_jwt(
    claims: dict[str, Any],
    private_key: Any,
    *,
    alg: str,
    kid: str | None = "key-1",
    header_overrides: dict[str, Any] | None = None,
) -> str:
    header: dict[str, Any] = {"alg": alg, "typ": "JWT"}
    if kid is not None:
        header["kid"] = kid
    header.update(header_overrides or {})
    signing_input = (
        f"{b64url(json.dumps(header).encode())}."
        f"{b64url(json.dumps(claims).encode())}"
    ).encode("ascii")
    if alg == "RS256":
        signature = private_key.sign(
            signing_input, padding.PKCS1v15(), hashes.SHA256()
        )
    elif alg == "ES256":
        der = private_key.sign(signing_input, ec.ECDSA(hashes.SHA256()))
        r, s = decode_dss_signature(der)
        signature = _int_bytes(r, length=32) + _int_bytes(s, length=32)
    else:
        msg = f"unsupported test alg {alg}"
        raise AssertionError(msg)
    return f"{signing_input.decode()}.{b64url(signature)}"


def base_claims(**overrides: Any) -> dict[str, Any]:
    claims: dict[str, Any] = {
        "iss": ISSUER,
        "aud": CLIENT_ID,
        "sub": "oidc-subject-1",
        "iat": NOW_S - 10,
        "exp": NOW_S + 300,
        "nonce": "nonce-value",
        "groups": ["mdgw-operators"],
        "name": "Ada Operator",
        "email": "ada@example.com",
    }
    claims.update(overrides)
    return claims


@dataclass
class FakeResponse:
    status: int
    body: bytes


class FakeTransport:
    """Records requests and returns canned discovery/JWKS/token responses."""

    def __init__(self) -> None:
        self.requests: list[tuple[str, str, bytes | None, float]] = []
        self.provider_document: dict[str, Any] = {
            "issuer": ISSUER,
            "authorization_endpoint": f"{ISSUER}/authorize",
            "token_endpoint": f"{ISSUER}/token",
            "jwks_uri": f"{ISSUER}/jwks",
        }
        self.jwks: dict[str, Any] = {"keys": []}
        self.jwks_sequence: list[dict[str, Any]] = []
        self.token_response: dict[str, Any] = {"id_token": "id-token"}
        self.token_status = 200
        self.fail_with: Exception | None = None

    def __call__(
        self, request: Any, *, timeout: float
    ) -> FakeResponse:
        url = request.full_url
        self.requests.append(
            (
                request.get_method(),
                url,
                request.data,
                timeout,
            )
        )
        if self.fail_with is not None:
            raise self.fail_with
        if url.endswith("/.well-known/openid-configuration"):
            return FakeResponse(200, json.dumps(self.provider_document).encode())
        if url == f"{ISSUER}/jwks":
            document = (
                self.jwks_sequence.pop(0)
                if self.jwks_sequence
                else self.jwks
            )
            return FakeResponse(200, json.dumps(document).encode())
        if url == f"{ISSUER}/token":
            return FakeResponse(
                self.token_status, json.dumps(self.token_response).encode()
            )
        msg = f"unexpected URL {url}"
        raise AssertionError(msg)

    def count(self, suffix: str) -> int:
        return sum(
            1
            for _method, url, _data, _t in self.requests
            if url.endswith(suffix)
        )


def _client(
    transport: FakeTransport,
    *,
    clock: Any = None,
    config: AdminOidcConfig | None = None,
    environ: dict[str, str] | None = None,
    **config_overrides: Any,
) -> OidcClient:
    settings = config or AdminOidcConfig(
        issuer=ISSUER,
        client_id=CLIENT_ID,
        client_secret_env="MDGW_OIDC_CLIENT_SECRET",  # ruff: ignore[hardcoded-password-func-arg]
        role_mapping={"mdgw-operators": "Operator"},
        **config_overrides,
    )
    return OidcClient(
        settings,
        transport=transport,
        clock=clock or (lambda: NOW_NS),
        environ=(
            {"MDGW_OIDC_CLIENT_SECRET": SECRET}
            if environ is None
            else environ
        ),
    )


# -- discovery --------------------------------------------------------------


def test_discovery_is_cached_for_a_bounded_ttl() -> None:
    transport = FakeTransport()
    now = {"ns": NOW_NS}
    client = _client(
        transport, clock=lambda: now["ns"], discovery_ttl_s=60.0
    )

    first = client.discovery()
    second = client.discovery()

    assert first == second
    assert first.issuer == ISSUER
    assert first.authorization_endpoint == f"{ISSUER}/authorize"
    assert first.token_endpoint == f"{ISSUER}/token"
    assert first.jwks_uri == f"{ISSUER}/jwks"
    assert transport.count("/.well-known/openid-configuration") == 1
    assert transport.requests[0][3] == pytest.approx(5.0)

    now["ns"] = NOW_NS + 61 * 1_000_000_000
    client.discovery()
    assert transport.count("/.well-known/openid-configuration") == 2


def test_discovery_ttl_is_capped() -> None:
    transport = FakeTransport()
    now = {"ns": NOW_NS}
    client = _client(
        transport, clock=lambda: now["ns"], discovery_ttl_s=10_000.0
    )
    client.discovery()
    now["ns"] = NOW_NS + 3_601 * 1_000_000_000

    client.discovery()

    assert transport.count("/.well-known/openid-configuration") == 2


