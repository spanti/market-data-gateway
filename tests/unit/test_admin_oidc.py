# -- PKCE / authorize -------------------------------------------------------


def test_pkce_challenge_is_s256_of_the_verifier() -> None:
    verifier = "a" * 43

    expected = b64url(hashlib.sha256(verifier.encode("ascii")).digest())
    assert pkce_challenge(verifier) == expected


def test_authorization_url_carries_pkce_state_and_nonce() -> None:
    transport = FakeTransport()
    client = _client(transport)
    verifier = "verifier-" + "x" * 43

    url = client.authorization_url(
        state="state-value",
        nonce="nonce-value",
        code_challenge=pkce_challenge(verifier),
        redirect_uri="https://console.example.com/api/v1/admin/auth/callback",
    )

    parts = urlsplit(url)
    query = parse_qs(parts.query)
    assert f"{parts.scheme}://{parts.netloc}" == ISSUER
    assert parts.path == "/authorize"
    assert query["response_type"] == ["code"]
    assert query["client_id"] == [CLIENT_ID]
    assert query["state"] == ["state-value"]
    assert query["nonce"] == ["nonce-value"]
    assert query["code_challenge_method"] == ["S256"]
    assert query["code_challenge"] == [pkce_challenge(verifier)]
    assert query["scope"] == ["openid profile email"]
    assert (
        query["redirect_uri"]
        == ["https://console.example.com/api/v1/admin/auth/callback"]
    )


# -- token exchange ---------------------------------------------------------


def test_token_exchange_posts_pkce_and_client_secret_from_env() -> None:
    transport = FakeTransport()
    client = _client(transport)

    id_token = client.exchange_code(
        code="code-123",
        code_verifier="verifier-value",
        redirect_uri="https://console.example.com/callback",
    )

    assert id_token == "id-token"  # ruff: ignore[hardcoded-password-string]
    method, url, body, _timeout = transport.requests[-1]
    assert method == "POST"
    assert url == f"{ISSUER}/token"
    assert body is not None
    form = parse_qs(body.decode("ascii"))
    assert form["grant_type"] == ["authorization_code"]
    assert form["code"] == ["code-123"]
    assert form["client_id"] == [CLIENT_ID]
    assert form["client_secret"] == [SECRET]
    assert form["code_verifier"] == ["verifier-value"]
    assert form["redirect_uri"] == ["https://console.example.com/callback"]


def test_missing_client_secret_environment_value_fails_closed() -> None:
    transport = FakeTransport()
    client = _client(transport, environ={})

