// Optional installed browser channel (for example "chrome" or "msedge") when
// downloading Playwright's bundled Chromium is not possible on this host.
// The environment variable always wins; otherwise use an installed Chrome/Edge
// on Windows and fall back to Playwright's bundled Chromium elsewhere.
function detectBrowserChannel(): string | undefined {
  if (process.env.MDGW_E2E_CHANNEL) {
    return process.env.MDGW_E2E_CHANNEL;
  }
  if (process.platform !== "win32") {
    return undefined;
  }
  const candidates: Array<[executable: string, channel: string]> = [
    ["C:/Program Files/Google/Chrome/Application/chrome.exe", "chrome"],
    ["C:/Program Files (x86)/Google/Chrome/Application/chrome.exe", "chrome"],
    [
      "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
      "msedge",
    ],
    ["C:/Program Files/Microsoft/Edge/Application/msedge.exe", "msedge"],
  ];
  for (const [executable, channel] of candidates) {
    if (fs.existsSync(executable)) {
      return channel;
    }
  }
  return undefined;
}

const browserChannel = detectBrowserChannel();

const generatedDir = path.join(dirname, ".playwright-tmp");
const serverScriptPath = path.join(generatedDir, "api-server.py");

const serverScript = String.raw`# Generated by playwright.config.ts for a throwaway acceptance Dataset.
import json
import os
import shutil
import sys
import time
import urllib.parse
import urllib.request
from datetime import UTC, datetime
from pathlib import Path

repo = Path(r"__REPO__")
os.chdir(repo)
sys.path.insert(0, str(repo / "src"))

root = Path(r"__DATA_ROOT__")
if root.exists():
    shutil.rmtree(root)
root.mkdir(parents=True, exist_ok=True)

from mdgw.config import load_config
from mdgw.ingest.fake import BarInput, FakeFeedHandler
from mdgw.runtime import GatewayRuntime

cfg = load_config(repo / "config" / "gateway.toml")
cfg = cfg.model_copy(update={
    "server": cfg.server.model_copy(update={"host": "127.0.0.1", "http_port": __API_PORT__}),
    "storage": cfg.storage.model_copy(update={"flush_max_bytes": 0, "flush_max_age_s": 0}),
})

feed = FakeFeedHandler(
    instrument_id="binance:BTC/USDT",
    bars=[
        BarInput(
            open_ts=datetime(2024, 1, 1, 0, 0, tzinfo=UTC),
            open="65000.1", high="65010.0", low="64990.0",
            close="65005.5", volume="12.34", trade_count=128,
        ),
        BarInput(
            open_ts=datetime(2024, 1, 1, 0, 1, tzinfo=UTC),
            open="65005.5", high="65020.0", low="65000.0",
            close="65015.0", volume="10.5", trade_count=64,
        ),
    ],
)

rt = GatewayRuntime(feed_handler=feed, config=cfg, data_root=root)
rt.start()
rt.ingest()

query = urllib.parse.urlencode({
    "interval": "1m",
    "instrument": "binance:BTC/USDT",
    "limit": "100",
    "start": "2024-01-01T00:00:00Z",
    "end": "2024-01-01T00:02:00Z",
})
probe = f"http://127.0.0.1:__API_PORT__/api/v1/bars?{query}"
for _ in range(100):
    try:
        with urllib.request.urlopen(probe, timeout=1) as response:
            body = json.load(response)
        if len(body.get("bars", [])) >= 2:
            break
    except Exception:
        pass
    time.sleep(0.1)
print("READY", flush=True)

try:
    while True:
        time.sleep(3600)
except KeyboardInterrupt:
    pass
finally:
    rt.stop()
`
  .replace("__REPO__", repo)
  .replace("__DATA_ROOT__", dataRoot)
  .replace("__API_PORT__", String(apiPort));

